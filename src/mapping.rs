pub fn pair(a: char, b: char) -> Option<&'static str> {
    match (a, b) {
        ('わ', '゙') => Some("va"),
        ('ゑ', '゙') => Some("ve"),
        ('を', '゙') => Some("vo"),
        ('ㇷ', '゚') => Some("p"),
        ('し', 'ゃ') => Some("sha"),
        ('し', 'ゅ') => Some("shu"),
        ('し', 'ょ') => Some("sho"),
        ('じ', 'ゃ') => Some("ja"),
        ('じ', 'ゅ') => Some("ju"),
        ('じ', 'ょ') => Some("jo"),
        ('ち', 'ゃ') => Some("cha"),
        ('ち', 'ゅ') => Some("chu"),
        ('ち', 'ょ') => Some("cho"),
        _ => None,
    }
}
